// Regenerates lib/invoice-assets.generated.ts from the invoice's artwork and
// fonts, as base64, so the PDF renderer needs no file access at run time (a
// serverless function does not ship `public/` unless told to).
//
//   node scripts/build-invoice-assets.mjs
//
// Inputs:
//   public/invoice/iitpkd-wordmark.jpg  header, left  (word/media/image1.jpg of public/GHM_Invoice.docx)
//   public/invoice/iitpkd-logo.png      header, right (word/media/image2.gif, converted)
//   public/invoice/hindi-address.png    the Hindi half of the footer address line, rendered from
//                                       the template's own Palanquin Dark Bold — jsPDF cannot shape
//                                       Devanagari, so it is artwork, never text
//                                       (Palanquin Dark is SIL OFL; its licence is in assets/invoice/fonts.)
//   assets/invoice/fonts/Arimo-*.ttf    Arimo (metric-compatible with the template's Arial, and it
//                                       has ₹), subset to Latin-1 + ₹. SIL Open Font License, beside it.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(root, p)).toString("base64");

const assets = {
  wordmarkJpg: read("public/invoice/iitpkd-wordmark.jpg"),
  logoPng: read("public/invoice/iitpkd-logo.png"),
  hindiAddressPng: read("public/invoice/hindi-address.png"),
  arimoRegular: read("assets/invoice/fonts/Arimo-Regular.ttf"),
  arimoBold: read("assets/invoice/fonts/Arimo-Bold.ttf"),
};

const body = Object.entries(assets)
  .map(([k, v]) => `export const ${k} =\n  "${v}";\n`)
  .join("\n");

fs.writeFileSync(
  path.join(root, "lib/invoice-assets.generated.ts"),
  `// Generated by scripts/build-invoice-assets.mjs — do not edit by hand.\n` +
    `// Base64 of the invoice artwork and fonts; see that script for where each comes from.\n` +
    `import "server-only";\n\n` +
    body
);
console.log("wrote lib/invoice-assets.generated.ts");
